import { useState } from "react";
import { useMutation, useQuery } from "@tanstack/react-query";
import {
  generateNoticeDraft,
  getErrorMessage,
  getNoticeEvidence,
  saveNoticeDraft,
} from "../../api/client";
import type { NoticeDetail } from "../../types";

/**
 * The response to the notice.
 *
 * "Generate" builds a first pass from the client's own reconciliation records,
 * which are listed under Evidence so a reviewer can see exactly what it drew
 * on. The draft marks each fact with the record it came from, like [E2], and
 * anything the records could not answer is left as a placeholder for the
 * practitioner.
 */
export default function NoticeDraftPanel({
  notice,
  onChanged,
}: {
  notice: NoticeDetail;
  onChanged: (n: NoticeDetail) => void;
}) {
  const [text, setText] = useState(notice.drafted_response ?? "");
  const [showEvidence, setShowEvidence] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [saved, setSaved] = useState(false);

  const editable = notice.editable.draft;
  const meta = notice.ai_analysis?.draft;
  const hasDraft = Boolean(notice.drafted_response?.trim());
  const dirty = text !== (notice.drafted_response ?? "");

  const evidence = useQuery({
    queryKey: ["notice-evidence", notice.id],
    queryFn: () => getNoticeEvidence(notice.id),
    enabled: showEvidence,
  });

  const save = useMutation({
    mutationFn: () => saveNoticeDraft(notice.id, text),
    onSuccess: (n) => {
      setError(null);
      setSaved(true);
      window.setTimeout(() => setSaved(false), 2500);
      onChanged(n);
    },
    onError: (err) => setError(getErrorMessage(err)),
  });

  const generate = useMutation({
    mutationFn: (replace: boolean) => generateNoticeDraft(notice.id, replace),
    onSuccess: (n) => {
      setError(null);
      setText(n.drafted_response ?? "");
      onChanged(n);
    },
    onError: (err) => setError(getErrorMessage(err)),
  });

  function onGenerate() {
    if ((hasDraft || dirty) && !window.confirm("This replaces the current draft, including any edits. Continue?")) {
      return;
    }
    generate.mutate(hasDraft || dirty);
  }

  return (
    <section className="rounded-lg border border-slate-200 bg-white p-4 shadow-sm">
      <div className="flex flex-wrap items-center gap-3">
        <h2 className="text-sm font-semibold text-slate-900">Response</h2>
        {editable && (
          <button
            onClick={onGenerate}
            disabled={generate.isPending}
            className="ml-auto rounded border border-slate-300 px-3 py-1 text-sm text-slate-700 hover:bg-slate-50 disabled:opacity-50"
          >
            {generate.isPending ? "Drafting…" : "Generate from reconciliation records"}
          </button>
        )}
      </div>

      {notice.rework_reason && notice.status === "UNDER_REVIEW" && (
        <p className="mt-3 rounded border border-amber-200 bg-amber-50 px-3 py-2 text-sm text-amber-900">
          <span className="font-medium">Sent back for changes:</span> {notice.rework_reason}
        </p>
      )}

      {!editable && !hasDraft && (
        <p className="mt-3 text-sm text-slate-500">
          {notice.status === "RECEIVED"
            ? "Start the review to begin drafting a response."
            : "No response was drafted."}
        </p>
      )}

      {(editable || hasDraft) && (
        <textarea
          value={text}
          onChange={(e) => {
            setSaved(false);
            setText(e.target.value);
          }}
          readOnly={!editable}
          rows={18}
          aria-label="Response to the notice"
          placeholder="Write the response, or generate a first pass from the reconciliation records."
          className={`mt-3 w-full rounded border border-slate-300 px-3 py-2 font-mono text-xs leading-relaxed ${
            editable ? "" : "bg-slate-50"
          }`}
        />
      )}

      {editable && (
        <div className="mt-2 flex items-center gap-3">
          <button
            onClick={() => save.mutate()}
            disabled={!dirty || save.isPending || !text.trim()}
            className="rounded bg-slate-900 px-4 py-1.5 text-sm font-medium text-white hover:bg-slate-800 disabled:opacity-40"
          >
            {save.isPending ? "Saving…" : "Save draft"}
          </button>
          {saved && <span className="text-sm text-emerald-700">Saved.</span>}
          {dirty && <span className="text-xs text-amber-700">Unsaved changes</span>}
        </div>
      )}

      {meta && hasDraft && (
        <div className="mt-4 space-y-2 rounded border border-slate-200 bg-slate-50 p-3 text-xs text-slate-700">
          <p>
            First pass generated by {meta.provider === "mock" ? "the local rule-based drafter" : meta.model} from{" "}
            {meta.evidence_count} reconciliation record{meta.evidence_count === 1 ? "" : "s"}. It
            is a starting point: read every line before it goes anywhere.
          </p>
          {meta.unverified_amounts.length > 0 && (
            <p className="font-medium text-amber-800">
              These amounts appear in the draft but not in the records or the notice, so check them:{" "}
              {meta.unverified_amounts.map((a) => `₹${a}`).join(", ")}
            </p>
          )}
          {meta.open_points.length > 0 && (
            <div>
              <div className="font-medium">Still to be completed by you</div>
              <ul className="list-disc pl-5">
                {meta.open_points.map((p) => (
                  <li key={p}>{p}</li>
                ))}
              </ul>
            </div>
          )}
          {meta.evidence_gaps.length > 0 && (
            <div>
              <div className="font-medium">Gaps in the records</div>
              <ul className="list-disc pl-5">
                {meta.evidence_gaps.map((g) => (
                  <li key={g}>{g}</li>
                ))}
              </ul>
            </div>
          )}
        </div>
      )}

      <div className="mt-4 border-t border-slate-100 pt-3">
        <button
          onClick={() => setShowEvidence((v) => !v)}
          className="text-sm text-slate-700 underline hover:text-slate-900"
        >
          {showEvidence ? "Hide the records this draws on" : "Show the records this draws on"}
        </button>
        {showEvidence && (
          <div className="mt-2 text-sm">
            {evidence.isLoading && <p className="text-slate-500">Loading…</p>}
            {evidence.isError && <p className="text-rose-700">{getErrorMessage(evidence.error)}</p>}
            {evidence.data && (
              <>
                {evidence.data.gaps.map((g) => (
                  <p key={g} className="mb-1 text-amber-800">
                    {g}
                  </p>
                ))}
                {evidence.data.items.length === 0 && (
                  <p className="text-slate-500">
                    No reconciliation records are available for this notice, so a draft would
                    contain placeholders only.
                  </p>
                )}
                <ul className="space-y-1">
                  {evidence.data.items.map((i) => (
                    <li key={i.id} className="flex gap-2 text-slate-800">
                      <span className="font-mono text-xs text-slate-500">[{i.id}]</span>
                      <span>{i.text}</span>
                    </li>
                  ))}
                </ul>
              </>
            )}
          </div>
        )}
      </div>

      {error && (
        <p role="alert" className="mt-3 text-sm text-rose-700">
          {error}
        </p>
      )}
    </section>
  );
}
