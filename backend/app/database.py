"""
Database engine/session setup.

Local development runs on SQLite; staging and production point
DATABASE_URL at PostgreSQL. The only driver-specific detail is the
SQLite `check_same_thread` flag, which is applied conditionally so the
same code works against both.
"""
from sqlalchemy import MetaData, create_engine
from sqlalchemy.orm import sessionmaker, declarative_base

from app.config import settings

# `check_same_thread=False` is a SQLite-only escape hatch that lets the
# connection be used across FastAPI's threadpool. Passing it to psycopg
# would raise, so it is applied only for SQLite URLs.
_connect_args = {"check_same_thread": False} if settings.is_sqlite else {}

_engine_kwargs = {
    "connect_args": _connect_args,
    "echo": False,
}
if not settings.is_sqlite:
    # Pooling settings only matter for a real networked database.
    _engine_kwargs.update(pool_pre_ping=True, pool_size=5, max_overflow=10)

engine = create_engine(settings.database_url, **_engine_kwargs)
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)

# Every constraint gets a deterministic name. SQLite cannot ALTER a table in
# place, so Alembic rebuilds it in "batch" mode — and a rebuild can only
# recreate a constraint it can name. Without this convention, autogenerated
# migrations emit unnamed constraints and fail with "Constraint must have a
# name" the first time a table is altered.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

Base = declarative_base(metadata=MetaData(naming_convention=NAMING_CONVENTION))


def get_db():
    """FastAPI dependency that yields a DB session and always closes it."""
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


def init_db():
    """Create all tables directly from the ORM metadata.

    Schema changes are owned by Alembic (`alembic upgrade head`). This
    helper remains for tests and for the seed script, which build a
    throwaway database from scratch and then stamp it as up to date.
    """
    from app import models  # noqa: F401  (ensure models are registered)
    Base.metadata.create_all(bind=engine)
